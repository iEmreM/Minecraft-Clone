WATER = 8

# What the mesher does with a block: 0 is a cube and goes down the greedy path,
# -1 is not drawn at all, and anything positive indexes world/shapes.py. One
# table replaces the `!= AIR and != WATER` the mask loop used to open with, so
# adding a shape costs the hot loop nothing it was not already paying.
#
# Passed into build_chunk_mesh_fast as an argument for the same reason
# FACE_LAYER is — @njit(cache=True) freezes globals into the cached artifact.
SHAPE_OF = np.zeros(max(BLOCK_NAMES) + 1, dtype=np.int32)
SHAPE_OF[0] = -1                    # AIR
SHAPE_OF[WATER] = -1                # drawn as one flat plane, not as blocks
for _bid, _shape in SHAPE_NAME.items():
    SHAPE_OF[_bid] = shapes.INDEX[_shape]

# Everything the mesher needs about shapes, as one argument. A tuple rather
