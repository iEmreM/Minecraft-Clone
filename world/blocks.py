# ---------------------------------------------------------------------------
# Oriented blocks
# ---------------------------------------------------------------------------
# A door has to face somewhere and `ModernChunk.blocks` is one id per cell with
# no room for a state byte, so the four facings are four block ids and the
# picker shows one of them. That is the cheap half of what the real game's
# `BlockState` does, and it is enough for the two families that need it: which
# way a door swings, and which wall a ladder is on.
#
# The three dicts below are what `main.py` places from. Everything they hold is
# generated by _door/_ladder, so the ids stay contiguous by construction and
# `base + facing` is the whole lookup.
FACING = {}          # base id -> the four ids, in shapes.FACING_NAMES order
UPPER = {}           # lower half -> upper half, for the two-block blocks
LOWER = {}           # and back again
_HIDDEN = set()      # variants the creative picker must not list
WALL_MOUNTED = set() # placed against the block that was clicked, not by yaw


def _expand(textures):
    """One / three / four / six texture names -> the six faces, in face_id order.

    Six is the escape hatch and it is written in face_id order, not the
    reference's: a shape whose model names five or six different textures (a
    lectern, a stonecutter) has nowhere else to put them.
    """
    if isinstance(textures, str):
        return (textures,) * 6
    if len(textures) == 6:
        return tuple(textures)
    if len(textures) == 3:
        top, side, bottom = textures
        front = side
    else:
        top, side, bottom, front = textures
    faces = [None] * 6
    faces[TOP] = top
    faces[BOTTOM] = bottom
    faces[FRONT] = front
    faces[BACK] = faces[RIGHT] = faces[LEFT] = side
    return tuple(faces)


# Which of the six faces looks out of each of the four horizontal facings, in
# FACING_NAMES order.
_FACING_FACE = (BACK, RIGHT, FRONT, LEFT)                # -Z, +X, +Z, -X


def _oriented(bid, name, faces, extra):
    """Four ids of one *cube*, its odd face turned to a different side in each.

    A furnace is a cube in every other respect, so this rotates `_expand`'s six
    face names instead of adding a shape: the greedy mesher, the atlas and the
    HUD icon all stay on the path they were already on, and the only new thing
    in the world is three more ids and three more rows of `FACE_LAYER`.

    The block keeps its own id for the facing `_expand` would have given it (+Z)
    so its icon does not move; the other three are *extra* onward and hidden
    from the picker. `main.orient` then places whichever one points back at the
    player, which is the real game's rule for a furnace as much as for a door.

    Only for the blocks whose front really differs from their sides — a
    cartography table's four sides are three different textures and rotating one
    of them would be a guess.
    """
    six = _expand(faces)
    side, front = six[BACK], six[FRONT]
    assert side != front, f'{name} has no front face to turn'
    ids, rows, n = [], [], 0
    for face in _FACING_FACE:
        if face == FRONT:
            ids.append(bid)
            rows.append((bid, name, faces))
            continue
        turned = list(six)
        turned[FRONT] = side
        turned[face] = front
        ids.append(extra + n)
        rows.append((extra + n, name, tuple(turned)))
        n += 1
    FACING[bid] = tuple(ids)
    _HIDDEN.update(i for i in ids if i != bid)
    return rows


def _variants(base, name, faces, shape_prefix, wall=False):
    """Four rows of one block, one per horizontal facing.

    *faces* is the texture spec every variant shares; the shape is
    `shape_prefix + '_' + facing`, which is how world/shapes.py names them.
    """
    FACING[base] = tuple(base + i for i in range(4))
    _HIDDEN.update(FACING[base][1:])
    if wall:
        WALL_MOUNTED.add(base)
    return [(base + i, name, faces, shape_prefix + '_' + facing)
            for i, facing in enumerate(shapes.FACING_NAMES)]


def _door(base, name, wood):
    """A door: two blocks tall, four facings, eight ids.

    The halves are separate blocks because they carry different textures, and
    `UPPER` is what lets one right-click place both and one left-click take both
    away — a door left as a floating top half is the thing that looks broken.
    """
    lower = _variants(base, name, wood + '_door_bottom', 'door')
    upper = _variants(base + 4, name, wood + '_door_top', 'door')
    _HIDDEN.add(base + 4)                 # the top half is never picked directly
    for i in range(4):
        UPPER[base + i] = base + 4 + i
        LOWER[base + 4 + i] = base + i
    return lower + upper


